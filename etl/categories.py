    ("Ортодонтия", r"миниимплант|брекет|элайнер|ортодонт|аппарат|хааса|ретейнер|каппа|трейнер|пластинк"),
    ("Имплантация", r"имплант|абатмент|формировател|синус|костн"),
    ("Гигиена", r"гигиен|air ?flow|фторир|отбеливан"),
    ("Ортопедия", r"коронк|вкладк|накладк|винир|протез|e\.?max|циркон|сплинт"),
